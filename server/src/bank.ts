// Original practice bank written for this artifact.
// Situational questions follow a concept first, exam focused study method:
// read the situation, find what the question really asks, use the plan or
// document first, evaluate before acting or escalating, and follow change
// control instead of making changes informally. No third party book text
// or published exam questions are reproduced here. Process names are
// generic standard terms.

export type DomainKey = "people" | "process" | "business";

